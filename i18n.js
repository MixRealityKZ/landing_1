const langKey = "neonshine-lang";

function currentLang() {
  const saved = localStorage.getItem(langKey);
  return saved === "en" ? "en" : "ru";
}

function applyLanguage(lang) {
  const dict = copy[lang];
  const page = document.body.dataset.page;
  document.documentElement.lang = lang;
  localStorage.setItem(langKey, lang);

  if (page && dict[`title.${page}`]) document.title = dict[`title.${page}`];
  const description = document.querySelector('meta[name="description"]');
  if (page && description && dict[`description.${page}`]) {
    description.setAttribute("content", dict[`description.${page}`]);
  }

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value != null) el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = dict[el.dataset.i18nAria];
    if (value != null) el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-service-key]").forEach((el) => {
    const key = el.dataset.serviceKey;
    el.dataset.service = dict[`service.${key}.name`];
    el.dataset.price = dict[`service.${key}.price`];
  });

  document.querySelectorAll("[data-wa-key]").forEach((el) => {
    el.dataset.wa = dict[el.dataset.waKey];
  });

  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    const active = button.dataset.setLang === lang;
    button.setAttribute("aria-pressed", String(active));
  });

  document.dispatchEvent(new CustomEvent("neonshine:lang"));
}

applyLanguage(currentLang());

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.setLang));
});
